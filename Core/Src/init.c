 void GPIOC10_Set_Output(void){
    SET_BIT(GPIOB->MODER, GPIO_MODER_MODE10_0);
    CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT10);
    SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR10_0);

    CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPD10_0);
 }
