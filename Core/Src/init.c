  void GPIO_Ini(void){
   SET_BIT(RCC->AHB1ENR, RCC_AHB1ENR_GPIOBEN | RCC_AHB1ENR_GPIOCEN); //включение тактироания gpiob и gpioc
   SET_BIT(GPIOB->MODER, GPIO_MODER_MODE7_0);

   CLEAR_BIT(GPIOB->OTYPER, GPIO_OTYPER_OT7); //настройка на PP работу 7 пина GPIOB 
   SET_BIT(GPIOB->OSPEEDR, GPIO_OSPEEDER_OSPEEDR7_0);//настройка скорости работы 7 пина на средн
   CLEAR_BIT(GPIOB->PUPDR, GPIO_PUPDR_PUPD7_0); //откл PU/PD резисторов для 7 пина  
 }
